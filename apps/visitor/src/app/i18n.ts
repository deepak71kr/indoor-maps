export type UiKey = keyof typeof ui;

export function tr(key: UiKey, params: Readonly<Record<string, string | number>> = {}): string {
  return ui[key].replace(/\{(\w+)\}/g, (m, name: string) =>
    name in params ? String(params[name]) : m,
  );
}

